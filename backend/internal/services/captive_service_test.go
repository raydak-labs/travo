// refreshBypassTimestamp races BypassDNS/RestoreDNS for the same file. It must
// take the same lock and rewrite atomically, so the file always parses.
func TestRefreshBypassTimestamp_ConcurrentWithBypassIsAtomic(t *testing.T) {
	cmd := &mockCmdRunner{responses: map[string]string{
		"uci get dhcp.@dnsmasq[0].noresolv":             "1",
		"uci get dhcp.@dnsmasq[0].server":               "127.0.0.1#5353",
		"uci get dhcp.@dnsmasq[0].rebind_protection":    "0",
		"uci set dhcp.@dnsmasq[0].noresolv=0":           "",
		"uci delete dhcp.@dnsmasq[0].server":            "",
		"uci add_list dhcp.@dnsmasq[0].server=10.1.2.3": "",
		"uci commit dhcp":                               "",
		"/etc/init.d/dnsmasq restart":                   "",
	}}
	svc, dir := newTestCaptiveServiceWithUCI(t, &MockHTTPProber{StatusCode: 204}, cmd)
	defer os.RemoveAll(dir)
	_ = svc.uci.Set("network", "wan", "peerdns", "1")

	if err := svc.BypassDNS(); err != nil {
		t.Fatalf("BypassDNS: %v", err)
	}

	// Hammer the guard file from another goroutine while refresh rewrites it.
	stop := make(chan struct{})
	done := make(chan struct{})
	go func() {
		defer close(done)
		for {
			select {
			case <-stop:
				return
			default:
			}
			data, err := os.ReadFile(svc.guardFile)
			if err != nil {
				continue
			}
			var b dnsBackup
			if err := json.Unmarshal(data, &b); err != nil {
				t.Errorf("guard file observed in a torn state: %v (content %q)", err, data)
				return
			}
		}
	}()
	for i := 0; i < 200; i++ {
		svc.refreshBypassTimestamp()
	}
	close(stop)
	<-done
}

// Stop must cancel the startup auto-restore goroutine and be idempotent.
func TestCaptiveService_StopIsIdempotentAndCancelsStartupGoroutine(t *testing.T) {
	svc := NewCaptiveServiceWithUCI(&MockHTTPProber{StatusCode: 204}, uci.NewMockUCI(), nil)
	done := make(chan struct{})
	go func() {
		svc.Stop()
		svc.Stop()
		close(done)
	}()
	select {
	case <-done:
	case <-time.After(5 * time.Second):
		t.Fatal("Stop did not return: the startup goroutine is not cancellable")
	}
}

