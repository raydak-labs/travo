// mockCmdRunner records calls and returns preset responses.
type mockCmdRunner struct {
	responses map[string]string
	calls     [][]string
	// blocked, when non-empty, makes every call whose key starts with it fail.
	// Tests flip it after a setup step to simulate a mid-flight failure.
	blocked string
}

func (m *mockCmdRunner) Run(name string, args ...string) ([]byte, error) {
	call := append([]string{name}, args...)
	m.calls = append(m.calls, call)
	key := name
	for _, a := range args {
		key += " " + a
	}
	if m.blocked != "" && strings.HasPrefix(key, m.blocked) {
		return nil, fmt.Errorf("blocked command: %s", key)
	}
	if resp, ok := m.responses[key]; ok {
		return []byte(resp), nil
	}
	return nil, fmt.Errorf("command not found: %s", key)
}

func newTestCaptiveServiceWithUCI(t *testing.T, prober HTTPProber, cmd *mockCmdRunner) (*CaptiveService, string) {
	u := uci.NewMockUCI()
	guardDir, _ := os.MkdirTemp("", "captive-test-*")
	guardFile := filepath.Join(guardDir, "dns-bypass-in-progress")
	svc := &CaptiveService{prober: prober, uci: u, cmd: cmd, guardFile: guardFile, stopCh: make(chan struct{})}
	// Bypass refuses to run without a DHCP-provided nameserver, so every test
	// gets a resolv.conf.auto containing one (same as a leased WAN uplink).
	svc.resolvConfAutoOverride = writeResolvAuto(t, guardDir, "10.1.2.3")
	return svc, guardDir
}

// writeResolvAuto writes a fake resolv.conf.auto with the given nameserver.
func writeResolvAuto(t *testing.T, dir, nameserver string) string {
	t.Helper()
	path := filepath.Join(dir, "resolv.conf.auto")
	if err := os.WriteFile(path, []byte("# generated by dhcp\nnameserver "+nameserver+"\n"), 0o600); err != nil {
		t.Fatalf("writing resolv.conf.auto: %v", err)
	}
	return path
}

// BypassDNS must abort when the DHCP nameserver is unknown: continuing would
// clear noresolv and drop the server list, leaving dnsmasq with no upstream.
func TestBypassDNS_AbortsWhenNoDHCPDNS(t *testing.T) {
	cmd := &mockCmdRunner{responses: map[string]string{
		"uci get dhcp.@dnsmasq[0].noresolv":          "1",
		"uci get dhcp.@dnsmasq[0].server":            "127.0.0.1#5353",
		"uci get dhcp.@dnsmasq[0].rebind_protection": "0",
	}}
	svc, dir := newTestCaptiveServiceWithUCI(t, &MockHTTPProber{StatusCode: 204}, cmd)
	defer os.RemoveAll(dir)
	// Empty nameserver file: no usable upstream can be discovered.
	svc.resolvConfAutoOverride = writeResolvAuto(t, dir, "")

	if err := svc.BypassDNS(); err == nil {
		t.Fatal("expected BypassDNS to abort without a DHCP nameserver")
	}
	if svc.IsDNSBypassed() {
		t.Error("guard file must not be created when bypass aborts")
	}
	for _, call := range cmd.calls {
		if len(call) > 1 && call[1] == "delete" {
			t.Errorf("must not touch dnsmasq server list, saw call %v", call)
		}
	}
}

