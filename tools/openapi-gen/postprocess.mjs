// Runs after orval:
//  1. Path parameters come from the router (section names, ids) and must be
//     encoded so a value such as `../system/reboot` cannot leave its route;
//     orval interpolates them raw.
//  2. shared/src/generated/paths.ts lists every served path, so API_ROUTES
//     can be type-checked against the contract.
import { readFileSync, writeFileSync } from 'node:fs';

const endpoints = '../../frontend/src/api/endpoints.ts';
const src = readFileSync(endpoints, 'utf8').replace(/return `(\/api\/[^`?]*)/g, (_, path) =>
  'return `' + path.replace(/\$\{(\w+)\}/g, '${encodeURIComponent(String($1))}'),
);
writeFileSync(endpoints, src);

const spec = JSON.parse(readFileSync('../../shared/openapi.json', 'utf8'));
const paths = Object.keys(spec.paths)
  .map((p) => p.replace(/\{(\w+)\}/g, ':$1'))
  .sort();
writeFileSync(
  '../../shared/src/generated/paths.ts',
  [
    '// Generated by tools/openapi-gen from shared/openapi.json. Do not edit.',
    '/** Every path the backend serves, with `{param}` written as `:param`. */',
    'export type ApiPath =',
    ...paths.map((p, i) => `  | '${p}'${i === paths.length - 1 ? ';' : ''}`),
    '',
  ].join('\n'),
);
